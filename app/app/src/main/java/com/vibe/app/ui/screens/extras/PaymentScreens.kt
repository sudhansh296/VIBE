/**
 * Payment result: success / failed / pending. DEMO. The result always comes from the SERVER after it checks the payment with
 * Razorpay; the app never adds coins by itself.
 */
@Composable
fun PaymentResultScreen(kind: String, onWallet: () -> Unit, onReceipt: () -> Unit, onSupport: () -> Unit) {
    when (kind) {
        "success" -> StateScreen(
            icon = MeIcons.Tick, tint = VibeColors.Green, circle = true, title = "Payment successful", subtitle = "2,000 coins have been added to your wallet.",
            primary = "Done", onPrimary = onWallet, secondary = "View receipt", onSecondary = onReceipt,
            content = { KeyValueCard(listOf("Pack" to "1,500 + 500 bonus coins", "Amount paid" to "₹99.00", "Method" to "UPI · rahul@okaxis", "Order id" to "VB-20261015-8841")) },
        )
        "pending" -> StateScreen(
            icon = MeIcons.Clock, tint = VibeColors.Gold, circle = true, title = "Payment is pending",
            subtitle = "We are waiting for your bank to confirm. Coins are added automatically as soon as it is confirmed. Please do not pay again.",
            primary = "Back to Wallet", onPrimary = onWallet, secondary = "Contact support", onSecondary = onSupport,
            content = { KeyValueCard(listOf("Amount" to "₹99.00", "Method" to "UPI · rahul@okaxis", "Status" to "Waiting for the bank", "Reference" to "VB-20261015-8843")) },
        )
        else -> StateScreen(
            icon = MeIcons.Close, tint = VibeColors.Red, circle = true, title = "Payment failed",
            subtitle = "Your payment did not go through. If money was deducted it is refunded to your account, usually within 24 hours. No coins were added.",
            primary = "Try again", onPrimary = onWallet, secondary = "Contact support", onSecondary = onSupport,
            content = { KeyValueCard(listOf("Amount" to "₹99.00", "Method" to "Card ••• 4242", "Reason" to "Bank declined the payment", "Reference" to "VB-20261015-8842")) },
        )
    }
}

/** Receipt for a coin purchase. DEMO; generated by the server (taxes and legal details are managed by VIBE). */
@Composable
fun ReceiptScreen(onBack: () -> Unit, onSupport: () -> Unit) {
    val ctx = LocalContext.current
    Box(Modifier.fillMaxSize().background(VibeColors.Dark)) {
        GlowBlob(VibeColors.Green, 280.dp, Modifier.align(Alignment.TopEnd).offset(100.dp, (-100).dp))
        Column(Modifier.fillMaxSize()) {
            PageHeader("Receipt", onBack)
            Column(Modifier.weight(1f).verticalScroll(rememberScrollState()).padding(horizontal = 20.dp)) {
                val shape = RoundedCornerShape(24.dp)
                Column(
                    Modifier.padding(top = 8.dp).fillMaxWidth().clip(shape).background(Brush.verticalGradient(listOf(Color(0xFF151521), Color(0xFF10101A)))).border(1.dp, VibeColors.Line, shape).padding(20.dp),
                    horizontalAlignment = Alignment.CenterHorizontally,
                ) {
                    Box(Modifier.size(56.dp).clip(CircleShape).border(2.dp, VibeColors.Green, CircleShape), contentAlignment = Alignment.Center) {
                        Icon(MeIcons.Tick, null, tint = VibeColors.Green, modifier = Modifier.size(28.dp))
                    }
                    Text("Payment received", color = VibeColors.TextMute, fontSize = 12.sp, modifier = Modifier.padding(top = 12.dp))
                    Text("₹99.00", color = Color.White, fontSize = 36.sp, fontWeight = FontWeight.Black, modifier = Modifier.padding(top = 4.dp))
                    Row(Modifier.padding(top = 8.dp), verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                        CoinDot(20.dp)
                        Text("+2,000 coins", color = VibeColors.Gold, fontWeight = FontWeight.SemiBold)
                    }
                    Box(Modifier.padding(vertical = 16.dp).fillMaxWidth().height(1.dp).background(Color.White.copy(alpha = 0.12f)))
                    KeyValueCard(
                        listOf(
                            "Date" to "15 Oct 2026, 11:20 am", "Pack" to "1,500 coins + 500 bonus", "Method" to "UPI · rahul@okaxis",
                            "Order id" to "VB-20261015-8841", "Payment id" to "pay_Qx81…k2Z", "Status" to "Paid",
                        ),
                        valueColor = { if (it == 5) VibeColors.Green else Color.White },
                    )
                }
                Row(Modifier.padding(top = 16.dp), horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                    GhostBtn("Download PDF", Modifier.weight(1f)) { ctx.toast("Receipt saved as PDF") }
                    GhostBtn("Share", Modifier.weight(1f)) { ctx.toast("Share sheet opens") }
                }
                Text(
                    "Problem with this payment?", color = VibeColors.TextMute, fontSize = 12.sp, textAlign = TextAlign.Center,
                    modifier = Modifier.fillMaxWidth().clickable(onClick = onSupport).padding(top = 16.dp),
                )
                Text(
                    "Coins are digital credits used inside VIBE. This receipt is generated by the VIBE server. Taxes and legal details are managed by VIBE.",
                    color = Color(0xFF4B5563), fontSize = 11.sp, lineHeight = 16.sp, textAlign = TextAlign.Center, modifier = Modifier.fillMaxWidth().padding(vertical = 20.dp),
                )
            }
        }
    }
}

@Composable
internal fun GhostBtn(text: String, modifier: Modifier, onClick: () -> Unit) {
    Box(
        modifier.height(48.dp).clip(RoundedCornerShape(16.dp)).background(VibeColors.Card).border(1.dp, VibeColors.Line, RoundedCornerShape(16.dp)).clickable(onClick = onClick),
        contentAlignment = Alignment.Center,
    ) { Text(text, color = Color.White, fontSize = 14.sp, fontWeight = FontWeight.SemiBold) }
}
